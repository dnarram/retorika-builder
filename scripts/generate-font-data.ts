import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { FONT_SOURCES } from "../packages/publisher/src/fonts.ts";

/**
 * Writes `packages/publisher/src/fontData/`: the shipped faces and their licences, as base64 — **one
 * module per package** and an `index.ts` that imports them all statically. The faces come from
 * `@fontsource`, the licences from `packages/publisher/licences/`, which `pnpm fonts:licences` reads
 * from each family's holders.
 *
 * **Why the bytes live in source rather than being read from `node_modules` at run time.** Three
 * attempts at reading them failed in the one place that matters — the download route, inside Next's
 * bundled server runtime — while every unit test passed:
 *
 *   1. `import.meta.resolve` → "is not a function" in that runtime.
 *   2. a dynamic `require.resolve` → "Cannot find module as expression is too dynamic".
 *   3. literal `require.resolve` of each `package.json` → Turbopack rewrote the resolved path to the
 *      placeholder `[project]/node_modules/...`, and the read then failed with ENOENT.
 *
 * The pattern is that a bundler treats module resolution as its own business, so the way to be certain
 * is to have nothing to resolve and no path to read. Base64 in a generated module is bundler-proof, is
 * deterministic, and keeps `@retorika/publisher` with no third-party **runtime** dependency at all —
 * which its own package comment has prized since it was written.
 *
 * **One module per package since sprint 29** (ADR 0055), where it was one file of 467 KB for eight
 * families: twenty-five, and forty after day 3, would make it a single module of well over a megabyte
 * that every diff and every editor opens whole. Split, a family that changes regenerates one file, a
 * family that leaves takes its file with it — this script removes what the table no longer names — and
 * the index leaves room for a lazy `import()` per family later without changing `fontDataFor`'s callers.
 *
 * It also makes condition 3 of sprint 14 checkable rather than asserted: `fonts.test.ts` compares the
 * decoded bytes against their sources, so "exactly as `@fontsource` ships them" is a test and not a
 * promise. Run `pnpm fonts:generate` after changing a pinned version or the table.
 *
 * **The output is already in the shape `biome format` gives it** — key on one line, the base64 on the
 * next — so a regeneration is a clean diff and not a reformatting one.
 */

const require_ = createRequire(import.meta.url);
const LICENCES = join(import.meta.dirname, "..", "packages", "publisher", "licences");
const OUT = join(import.meta.dirname, "..", "packages", "publisher", "src", "fontData");
const packageDir = (name: string) => dirname(require_.resolve(`${name}/package.json`));

/** `eb-garamond` → `ebGaramond`, `source-serif-4` → `sourceSerif4`: the slug as an identifier. */
const identifier = (slug: string) =>
  slug.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());

const HEADER = `// GENERATED by scripts/generate-font-data.ts — do not edit by hand. Regenerate with
// \`pnpm fonts:generate\`.`;

/** Every entry of one package: its faces, keyed by file name, and its licence, keyed by bundle path. */
const modules = new Map<string, string[]>();
for (const [name, source] of Object.entries(FONT_SOURCES)) {
  const slug = source.package.replace(/^@fontsource\//, "");
  const entries = modules.get(slug) ?? [];
  if (entries.length === 0) {
    // The holder's text from `packages/publisher/licences/`, never the package's `LICENSE`: that one
    // rebuilds its copyright line and can drop a Reserved Font Name (ADR 0045, amended sprint 29).
    const licence = readFileSync(join(LICENCES, `${slug}.txt`));
    entries.push(`  "${source.licencePath}":\n    "${licence.toString("base64")}",`);
  }
  const face = readFileSync(join(packageDir(source.package), "files", source.file));
  entries.push(`  "${name}":\n    "${face.toString("base64")}",`);
  modules.set(slug, entries);
}

mkdirSync(OUT, { recursive: true });
const slugs = [...modules.keys()].sort();
let bytes = 0;
for (const slug of slugs) {
  const file = `${HEADER}
//
// One package's faces and the licence that travels beside them, base64-encoded, keyed exactly as
// \`BuildSiteOptions.fonts\` wants them. Read through \`./index.ts\`, never directly.

/** biome-ignore-all lint/style/useNamingConvention: these keys are file names, not identifiers. */
const DATA: Readonly<Record<string, string>> = {
${(modules.get(slug) ?? []).sort().join("\n")}
};

export default DATA;
`;
  writeFileSync(join(OUT, `${slug}.ts`), file);
  bytes += file.length;
}

const index = `${HEADER}
//
// The shipped faces and their licence texts, keyed exactly as \`BuildSiteOptions.fonts\` wants them: a
// face by its file name, a licence by the path it takes in the bundle. The faces are \`@fontsource\`'s
// files; the licences are the holders' texts in \`packages/publisher/licences/\`, never the package's
// rebuilt \`LICENSE\`. One module per package beside this one (ADR 0055).
//
// **In source rather than read from disk at run time**, because three different ways of resolving them
// from \`node_modules\` each worked in tests and failed inside Next's bundled server runtime. The
// generator's own comment records all three. \`packages/publisher/test/fonts.test.ts\` compares these
// bytes against their sources, so these files cannot drift from them.

${slugs.map((slug) => `import ${identifier(slug)} from "./${slug}.ts";`).join("\n")}

const BASE64: Readonly<Record<string, string>> = {
${slugs.map((slug) => `  ...${identifier(slug)},`).join("\n")}
};

/** The bytes for one entry, or \`undefined\` when this product ships no such file. */
export function fontDataFor(key: string): Uint8Array | undefined {
  const encoded = BASE64[key];
  return encoded === undefined ? undefined : Uint8Array.from(Buffer.from(encoded, "base64"));
}

/** Every key these modules carry, for the test that holds them level with \`FONT_SOURCES\`. */
export const FONT_DATA_KEYS: readonly string[] = Object.keys(BASE64);
`;
writeFileSync(join(OUT, "index.ts"), index);

// The directory is this script's: a module for a package the table no longer names leaves with it.
for (const file of readdirSync(OUT)) {
  if (file !== "index.ts" && !modules.has(file.replace(/\.ts$/, ""))) {
    rmSync(join(OUT, file));
    console.log(`generate-font-data: removed ${file}, no longer shipped`);
  }
}

console.log(
  `generate-font-data: wrote ${slugs.length} modules and an index, ${(bytes / 1024).toFixed(1)} KB`,
);
